package clase;

public class PersoanaVerificare {
    protected String nume;
    protected int varsta;
    protected boolean esteUrmaritaDePolitie;
    protected boolean areCreanteLaAlteBanci;

    public PersoanaVerificare(String nume, int varsta, boolean esteUrmaritaDePolitie, boolean areCreanteLaAlteBanci) {
        this.nume = nume;
        this.varsta = varsta;
        this.esteUrmaritaDePolitie = esteUrmaritaDePolitie;
        this.areCreanteLaAlteBanci = areCreanteLaAlteBanci;
    }
}
